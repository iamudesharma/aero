import 'dart:convert';
import 'dart:io';
import 'dart:math';

import 'package:aero/core/constants.dart';
import 'package:aero/core/contracts.dart';
import 'package:aero/core/crypto/sas_pairing.dart';
import 'package:aero/core/crypto/trust_store.dart';
import 'package:aero/core/models.dart';
import 'package:flutter_test/flutter_test.dart';

/// A controllable clock. The rate limiter and the proof expiry both read the
/// time through this, so tests never have to sleep.
class _FakeClock {
  _FakeClock(this._now);

  DateTime _now;

  DateTime call() => _now;

  void advance(Duration by) => _now = _now.add(by);
}

const String _fpA = 'a1b2c3d4e5f60718293a4b5c6d7e8f90a1b2c3d4e5f60718293a4b5c6d7e8f90';
const String _fpB = '00112233445566778899aabbccddeeff00112233445566778899aabbccddeeff';

/// A distinct, well-formed nonce for a given seed.
///
/// Must stay a *valid* base64url nonce: an earlier version generated bytes that
/// could exceed 255, which base64 correctly refused. Varying every byte (rather
/// than only the first) also means the sweep below really does sample different
/// transcripts rather than the same hash input truncated.
String _nonce(int seed) {
  final rng = Random(seed);
  final bytes = List<int>.generate(16, (_) => rng.nextInt(256));
  return base64Url.encode(bytes).replaceAll('=', '');
}

void main() {
  late Directory tmp;

  setUp(() async {
    tmp = await Directory.systemTemp.createTemp('aero_sas_test_');
  });

  tearDown(() async {
    if (await tmp.exists()) await tmp.delete(recursive: true);
  });

  group('deriveProof', () {
    final authority = SasPairingAuthority();

    test('is exactly six digits', () {
      final proof = authority.deriveProof(
        localFingerprint: _fpA,
        remoteFingerprint: _fpB,
        nonce: 'bm9uY2Ux',
      );
      expect(proof.value.length, Pairing.codeDigits);
      expect(RegExp(r'^\d{6}$').hasMatch(proof.value), isTrue,
          reason: 'got "${proof.value}"');
      expect(proof.method, Crypto.pairingMethod);
    });

    test('zero-pads rather than truncating', () {
      // Sweep enough nonces to be certain at least one value lands below 100000
      // (1-in-10 per draw) and confirm it keeps all six digits.
      var sawSmallValue = false;
      for (var i = 0; i < 400; i++) {
        final proof = authority.deriveProof(
          localFingerprint: _fpA,
          remoteFingerprint: _fpB,
          nonce: _nonce(i),
        );
        expect(proof.value.length, 6);
        if (proof.value.startsWith('0')) sawSmallValue = true;
      }
      expect(sawSmallValue, isTrue,
          reason: 'expected at least one code with a leading zero');
    });

    test('swapped fingerprint order yields the identical code', () {
      // This is the property that makes pairing work at all: the two sides never
      // agree on who dialled, so the derivation must be order-independent.
      final initiator = authority.deriveProof(
        localFingerprint: _fpA,
        remoteFingerprint: _fpB,
        nonce: 'bm9uY2Uy',
      );
      final responder = authority.deriveProof(
        localFingerprint: _fpB,
        remoteFingerprint: _fpA,
        nonce: 'bm9uY2Uy',
      );
      expect(responder.value, initiator.value);
    });

    test('swapped order still works when the fingerprints differ in length',
        () {
      // Length-first ordering has to agree with the swap even when the two
      // strings are not the same length, which is where a naive comparison can
      // break down.
      const short = 'ab';
      const long = 'abc';
      final a = authority.deriveProof(
        localFingerprint: short,
        remoteFingerprint: long,
        nonce: 'bm9uY2Uz',
      );
      final b = authority.deriveProof(
        localFingerprint: long,
        remoteFingerprint: short,
        nonce: 'bm9uY2Uz',
      );
      expect(b.value, a.value);
    });

    test('is case-insensitive', () {
      final lower = authority.deriveProof(
        localFingerprint: _fpA,
        remoteFingerprint: _fpB,
        nonce: 'bm9uY2U0',
      );
      final upper = authority.deriveProof(
        localFingerprint: _fpA.toUpperCase(),
        remoteFingerprint: _fpB.toUpperCase(),
        nonce: 'bm9uY2U0',
      );
      expect(upper.value, lower.value);
    });

    test('different nonces give different codes', () {
      final first = authority.deriveProof(
        localFingerprint: _fpA,
        remoteFingerprint: _fpB,
        nonce: 'bm9uY2Ux',
      );
      final second = authority.deriveProof(
        localFingerprint: _fpA,
        remoteFingerprint: _fpB,
        nonce: 'bm9uY2Uy',
      );
      expect(second.value, isNot(first.value));
    });

    test('different fingerprints give different codes', () {
      final first = authority.deriveProof(
        localFingerprint: _fpA,
        remoteFingerprint: _fpB,
        nonce: 'bm9uY2U1',
      );
      final second = authority.deriveProof(
        localFingerprint: _fpA,
        remoteFingerprint: 'ff${_fpB.substring(2)}',
        nonce: 'bm9uY2U1',
      );
      expect(second.value, isNot(first.value));
    });

    test('changes neither with the clock nor with derivation order', () {
      // The digest must not see DateTime.now(), or the two devices would
      // disagree whenever their clocks differ at all.
      final clock = _FakeClock(DateTime.utc(2026, 1, 1));
      final early = SasPairingAuthority(clock: clock.call).deriveProof(
        localFingerprint: _fpA,
        remoteFingerprint: _fpB,
        nonce: 'bm9uY2U2',
      );
      clock.advance(const Duration(days: 400));
      final late = SasPairingAuthority(clock: clock.call).deriveProof(
        localFingerprint: _fpA,
        remoteFingerprint: _fpB,
        nonce: 'bm9uY2U2',
      );
      expect(late.value, early.value);
      // ...but the expiry does move, so a code cannot live forever.
      expect(late.expiresAt.isAfter(early.expiresAt), isTrue);
    });

    test('spans the whole six-digit range, so it is not silently truncated',
        () {
      final seen = <int>{};
      for (var i = 0; i < 600; i++) {
        seen.add(int.parse(authority.deriveProof(
          localFingerprint: _fpA,
          remoteFingerprint: _fpB,
          nonce: _nonce(i),
        ).value));
      }
      // 10^6 possibilities; 600 draws should not all cluster in one decade.
      expect(seen.length, 600);
      expect(seen.every((v) => v >= 0 && v < 1000000), isTrue);
      expect(seen.reduce((a, b) => a > b ? a : b), greaterThan(99999));
    });
  });

  group('verifyProof', () {
    test('accepts a match', () {
      final authority = SasPairingAuthority();
      final proof = authority.deriveProof(
        localFingerprint: _fpA,
        remoteFingerprint: _fpB,
        nonce: 'bm9uY2U3',
      );
      expect(authority.verifyProof(proof, proof), isTrue);
      // The peer's independently derived proof carries a different expiry but
      // the same value; both must be unexpired.
      final peerProof = PairingProof(
        method: proof.method,
        value: proof.value,
        expiresAt: DateTime.now().add(const Duration(seconds: 30)),
      );
      expect(authority.verifyProof(proof, peerProof), isTrue);
    });

    test('rejects a different value', () {
      final authority = SasPairingAuthority();
      final mine = authority.deriveProof(
        localFingerprint: _fpA,
        remoteFingerprint: _fpB,
        nonce: 'bm9uY2U4',
      );
      final theirs = PairingProof(
        method: mine.method,
        value: mine.value == '000000' ? '000001' : '000000',
        expiresAt: DateTime.now().add(const Duration(seconds: 30)),
      );
      expect(authority.verifyProof(theirs, mine), isFalse);
      expect(authority.verifyProof(mine, theirs), isFalse);
    });

    test('rejects a different method', () {
      final authority = SasPairingAuthority();
      final proof = authority.deriveProof(
        localFingerprint: _fpA,
        remoteFingerprint: _fpB,
        nonce: 'bm9uY2U5',
      );
      final other = PairingProof(
        method: 'spake2',
        value: proof.value,
        expiresAt: proof.expiresAt,
      );
      expect(authority.verifyProof(other, proof), isFalse);
    });

    test('rejects once either side has expired', () {
      final clock = _FakeClock(DateTime.utc(2026, 1, 1));
      final authority = SasPairingAuthority(clock: clock.call);
      final proof = authority.deriveProof(
        localFingerprint: _fpA,
        remoteFingerprint: _fpB,
        nonce: 'bm9uY2U6',
      );
      expect(authority.verifyProof(proof, proof), isTrue);

      clock.advance(Pairing.codeLifetime + const Duration(seconds: 1));
      expect(authority.verifyProof(proof, proof), isFalse);

      final stillValid = authority.deriveProof(
        localFingerprint: _fpA,
        remoteFingerprint: _fpB,
        nonce: 'bm9uY2U3',
      );
      // Expected fresh, presented stale.
      expect(authority.verifyProof(stillValid, proof), isFalse);
      expect(authority.verifyProof(proof, stillValid), isFalse);
    });
  });

  group('rate limiting', () {
    test('blocks at maxAttempts and clears after the cooldown', () {
      final clock = _FakeClock(DateTime.utc(2026, 1, 1));
      final authority = SasPairingAuthority(clock: clock.call);
      const device = 'aabbccddeeff00112233445566778899';

      expect(authority.isRateLimited(device), isFalse);
      for (var i = 0; i < Pairing.maxAttempts - 1; i++) {
        authority.recordFailure(device);
        expect(authority.isRateLimited(device), isFalse,
            reason: 'must allow ${i + 1} of ${Pairing.maxAttempts}');
      }
      authority.recordFailure(device);
      expect(authority.isRateLimited(device), isTrue);

      // Still blocked a moment before the window closes.
      clock.advance(Pairing.attemptCooldown - const Duration(seconds: 1));
      expect(authority.isRateLimited(device), isTrue);

      clock.advance(const Duration(seconds: 2));
      expect(authority.isRateLimited(device), isFalse);
    });

    test('is per device', () {
      final authority = SasPairingAuthority();
      for (var i = 0; i < Pairing.maxAttempts; i++) {
        authority.recordFailure('attacker');
      }
      expect(authority.isRateLimited('attacker'), isTrue);
      expect(authority.isRateLimited('bystander'), isFalse);
    });

    test('spreads attempts across windows instead of blocking forever', () {
      final clock = _FakeClock(DateTime.utc(2026, 1, 1));
      final authority = SasPairingAuthority(clock: clock.call);
      const device = 'aabbccddeeff00112233445566778899';

      authority.recordFailure(device);
      clock.advance(const Duration(seconds: 30));
      authority.recordFailure(device);
      expect(authority.isRateLimited(device), isFalse);

      for (var i = 0; i < 3; i++) {
        authority.recordFailure(device);
      }
      expect(authority.isRateLimited(device), isTrue);

      authority.resetFailures(device);
      expect(authority.isRateLimited(device), isFalse);
    });
  });

  group('TrustStore', () {
    late TrustStore store;

    setUp(() {
      store = TrustStore(directory: tmp);
    });

    test('unknown before remembering, known after', () async {
      const device = 'aabbccddeeff00112233445566778899';
      final key = base64.encode(List<int>.filled(32, 0xAB));

      expect(
        await store.lookupTrust(deviceId: device, publicKey: key),
        TrustState.unknown,
      );

      await store.rememberPeer(deviceId: device, publicKey: key);
      expect(
        await store.lookupTrust(deviceId: device, publicKey: key),
        TrustState.known,
      );
    });

    test('same device id with a different key is an identity conflict',
        () async {
      const device = 'aabbccddeeff00112233445566778899';
      final realKey = base64.encode(List<int>.filled(32, 0xAB));
      final impostorKey = base64.encode(List<int>.filled(32, 0xCD));

      await store.rememberPeer(deviceId: device, publicKey: realKey);

      // This is the impersonation / reinstall case. It must not be trusted.
      expect(
        await store.lookupTrust(deviceId: device, publicKey: impostorKey),
        TrustState.identityConflict,
      );
      // ...and the original pin must survive the attempt.
      expect(
        await store.lookupTrust(deviceId: device, publicKey: realKey),
        TrustState.known,
      );
    });

    test('forgetPeer removes the pin and forgets failures', () async {
      const device = 'aabbccddeeff00112233445566778899';
      final key = base64.encode(List<int>.filled(32, 7));
      await store.rememberPeer(deviceId: device, publicKey: key);
      for (var i = 0; i < Pairing.maxAttempts; i++) {
        store.recordFailure(device);
      }
      expect(store.isRateLimited(device), isTrue);

      await store.forgetPeer(device);
      expect(
        await store.lookupTrust(deviceId: device, publicKey: key),
        TrustState.unknown,
      );
      expect(store.isRateLimited(device), isFalse);
    });

    test('persists across instances', () async {
      const device = 'aabbccddeeff00112233445566778899';
      final key = base64.encode(List<int>.filled(32, 3));
      await TrustStore(directory: tmp)
          .rememberPeer(deviceId: device, publicKey: key);

      // A fresh instance sharing the directory must see the pin.
      final reopened = TrustStore(directory: tmp);
      expect(
        await reopened.lookupTrust(deviceId: device, publicKey: key),
        TrustState.known,
      );
    });

    test('records an alias and a lastSeen timestamp', () async {
      const device = 'aabbccddeeff00112233445566778899';
      final key = base64.encode(List<int>.filled(32, 5));
      await store.rememberPeer(
        deviceId: device,
        publicKey: key,
        alias: 'Studio Mac',
      );
      final peers = await store.loadPeers();
      expect(peers, hasLength(1));
      expect(peers.single.alias, 'Studio Mac');
      expect(peers.single.lastSeenMs, greaterThan(0));

      // Re-remembering without an alias must not drop the existing one.
      await store.rememberPeer(deviceId: device, publicKey: key);
      expect((await store.loadPeers()).single.alias, 'Studio Mac');
    });

    test('a corrupt file reads as no peers instead of throwing', () async {
      const device = 'aabbccddeeff00112233445566778899';
      final key = base64.encode(List<int>.filled(32, 9));
      await store.rememberPeer(deviceId: device, publicKey: key);

      await File('${tmp.path}${Platform.pathSeparator}${TrustStore.fileName}')
          .writeAsString('{ this is not json');

      expect(await store.loadPeers(), isEmpty);
      expect(
        await store.lookupTrust(deviceId: device, publicKey: key),
        TrustState.unknown,
      );
      // And it must still be usable afterwards.
      await store.rememberPeer(deviceId: device, publicKey: key);
      expect(
        await store.lookupTrust(deviceId: device, publicKey: key),
        TrustState.known,
      );
    });

    test('malformed rows are dropped, valid rows survive', () async {
      final file = File(
          '${tmp.path}${Platform.pathSeparator}${TrustStore.fileName}');
      await file.writeAsString(jsonEncode(<String, dynamic>{
        'version': 1,
        'peers': <Object>[
          <String, dynamic>{},
          <String, dynamic>{'deviceId': 'x'},
          'not an object',
          <String, dynamic>{
            'deviceId': 'aabbccddeeff00112233445566778899',
            'publicKey': base64.encode(List<int>.filled(32, 11)),
          },
        ],
      }));
      final peers = await store.loadPeers();
      expect(peers, hasLength(1));
      expect(peers.single.deviceId, 'aabbccddeeff00112233445566778899');
    });

    test('delegates derivation, verification and rate limiting', () {
      // Composition check: TrustStore must behave like the authority it wraps.
      final direct = SasPairingAuthority();
      final mine = store.deriveProof(
        localFingerprint: _fpA,
        remoteFingerprint: _fpB,
        nonce: 'bm9uY2U3',
      );
      final theirs = direct.deriveProof(
        localFingerprint: _fpB,
        remoteFingerprint: _fpA,
        nonce: 'bm9uY2U3',
      );
      expect(mine.value, theirs.value);
      expect(store.verifyProof(mine, theirs), isTrue);

      for (var i = 0; i < Pairing.maxAttempts; i++) {
        store.recordFailure('device-x');
      }
      expect(store.isRateLimited('device-x'), isTrue);
      expect(store.pairing.isRateLimited('device-x'), isTrue);
    });

    test('satisfies the frozen interface', () {
      // Compile-time proof that TrustStore is usable wherever PairingAuthority
      // is required.
      final PairingAuthority authority = store;
      expect(authority, isA<TrustStore>());
    });
  });
}
/// Sending-side orchestrator: the object the UI drives.
///
/// [SenderSession] owns the whole sequence a transfer goes through — build an
/// [Offer], negotiate, stream bytes, verify, report completion — and it does so
/// without knowing anything about TLS, sockets, or even `dart:io`. Everything it
/// touches is injected as a [PeerLink] (bytes in and out), a [ChunkedFileReader]
/// (where the local bytes come from), and a [FileStore] (local disk facts such
/// as free space). That is what lets the same class drive a TCP/TLS link, a
/// WebRTC data channel, and the in-process fake the tests use.
///
/// ## Concurrency
///
/// Files run through a fixed-size worker pool of [Transfer.maxParallelFiles],
/// not `Future.wait` over everything. Two reasons:
///
///  * **Backpressure.** Each `putStream` pulls from its own file stream. Ten
///    concurrent pulls means ten file streams being read and ten 4 MiB buffers
///    live, plus ten TLS records in flight; one link's stall no longer holds up
///    an unrelated file's progress.
///  * **The constant exists for a reason.** The comments on
///    [Transfer.maxParallelFiles] record that beyond two, extra streams only
///    help on lossy links and actively hurt on clean Ethernet, where a single
///    stream already saturates the pipe. Honouring the constant rather than
///    picking a number locally keeps that measurement authoritative.
///
/// ## Progress
///
/// [progress] is a broadcast stream of per-file [FileProgress], throttled to at
/// most [_progressInterval] between events per file (plus one final event at
/// 100%). See [_emit] for why.

library;

import 'dart:async';
import 'dart:io';
import 'dart:math' as math;

import 'package:cryptography/cryptography.dart';
import 'package:uuid/uuid.dart';

import '../constants.dart';
import '../contracts.dart';
import '../logging.dart';
import '../models.dart';

/// Minimum wall-clock gap between progress events for one file.
///
/// 100 ms == 10 events/second per file, which is above the ~60 Hz refresh of any
/// realistic display and far above the rate at which a Flutter rebuild is
/// cheap. Emitting per chunk would mean up to 250 events/second per file on a
/// fast link (4 MiB chunks at 1 GB/s), each one rebuilding a `ProgressBar` and
/// re-laying-out a subtree. Coalescing here rather than in the UI keeps the
/// cost off the widget tree and keeps this class correct for any consumer.
const Duration _progressInterval = Duration(milliseconds: 100);

/// A file the user picked, resolved to real local bytes.
///
/// The id is generated by the caller (or by this class in [SenderSession.pick])
/// and is what the receiver keys its staging file on, so it must be unique
/// within one offer.
class LocalFile {
  const LocalFile({
    required this.id,
    required this.path,
    required this.name,
    required this.size,
    this.relPath,
    this.mtimeMs,
  });

  /// Unique within the offer. [Uuid] v4 by default.
  final String id;

  /// Absolute path on the local filesystem, read through a [ChunkedFileReader]
  /// (never directly, so a browser build can send without one).
  final String path;

  /// Basename shown to the receiving user.
  final String name;

  final int size;

  /// Path relative to the transfer root, for folder sends.
  final String? relPath;

  final int? mtimeMs;

  /// Wire form. [FileEntry.sha256] is intentionally left null here: it is filled
  /// in by [SenderSession] once the digest is known, before the offer goes out.
  FileEntry toEntry({String? sha256}) => FileEntry(
    id: id,
    name: name,
    size: size,
    relPath: relPath,
    sha256: sha256,
    mtimeMs: mtimeMs,
  );

  /// Builds a [LocalFile] from a real path, reading the size off disk.
  ///
  /// Uses `File.lengthSync` because this runs once per picked file on the UI
  /// isolate's critical path; a stat is cheap and the alternative is an await
  /// per file for no benefit.
  static LocalFile fromPath(
    String path, {
    String? id,
    String? relPath,
    int? size,
  }) {
    final file = File(path);
    final segments = path.split(Platform.pathSeparator);
    return LocalFile(
      id: id ?? const Uuid().v4(),
      path: file.absolute.path,
      name: segments.last,
      size: size ?? file.lengthSync(),
      relPath: relPath,
      mtimeMs: file.lastModifiedSync().millisecondsSinceEpoch,
    );
  }

  @override
  String toString() => 'LocalFile($name, $size bytes)';
}

/// Outcome of one [SenderSession.send].
class SendResult {
  const SendResult({
    required this.sessionId,
    required this.completed,
    this.rejected = const [],
    this.failures = const <String, String>{},
    this.cancelled = false,
    this.verdict,
  });

  /// The offer's session id, useful for correlating with the receiver's UI.
  final String sessionId;

  /// Entries the peer accepted *and* we finished sending and it verified.
  final List<FileEntry> completed;

  /// (fileId, reason) pairs from the peer's answer to our offer, verbatim.
  final List<(String, RejectReason)> rejected;

  /// Human-readable per-file errors (digest mismatch, transport failure).
  final Map<String, String> failures;

  final bool cancelled;

  /// The peer's final `/v1/complete` verdict, when we got that far.
  final CompletionResult? verdict;

  /// True when nothing failed and the peer confirmed the whole session.
  bool get ok => failures.isEmpty && (verdict?.ok ?? false);

  /// Total bytes across [completed] and nothing else — the only byte count that
  /// is known-good.
  int get bytesSent => completed.fold<int>(0, (a, e) => a + e.size);

  @override
  String toString() =>
      'SendResult(ok=$ok, ${completed.length} sent, ${rejected.length} rejected, '
      '${failures.length} failed)';
}

/// Drives a whole outgoing transfer against one [PeerLink].
class SenderSession {
  SenderSession({
    required PeerLink link,
    required ChunkedFileReader reader,
    required FileStore store,
    String? sessionId,
    int? maxParallel,
    int maxResumeAttempts = 2,
    Uuid uuid = const Uuid(),
  }) : // The lint would prefer `this._link`, but Dart forbids private named
       // parameters, so a public name is the only legal spelling here.
       // ignore: prefer_initializing_formals
       _link = link,
       // ignore: prefer_initializing_formals
       _reader = reader,
       // ignore: prefer_initializing_formals
       _store = store,
       _sessionId = sessionId ?? uuid.v4(),
       _maxParallel = (maxParallel ?? Transfer.maxParallelFiles).clamp(1, 32),
       _maxResumeAttempts = maxResumeAttempts.clamp(0, 8);

  final PeerLink _link;
  final ChunkedFileReader _reader;
  final FileStore _store;
  final String _sessionId;
  final int _maxParallel;

  /// How many times a file may be re-attempted after a `409 conflict` before
  /// the session gives up on it. Bounded because a peer that keeps disagreeing
  /// about the resume point must not turn into an infinite loop.
  final int _maxResumeAttempts;

  final StreamController<FileProgress> _progress =
      StreamController<FileProgress>.broadcast();

  /// Last event timestamp per file id, for throttling. Only touched from the
  /// single isolate that owns this session, so no synchronisation needed.
  final Map<String, DateTime> _lastProgress = {};

  /// Per-file transfer state, so a throttled update can still report the
  /// current state instead of guessing.
  final Map<String, TransferState> _states = {};

  /// Per-file byte counters.
  final Map<String, int> _bytes = {};

  Future<SendResult>? _inFlight;
  bool _cancelRequested = false;

  /// The id this session will use in its offer. Stable across a resume, which is
  /// what lets the receiver match the new offer to the staged files from the
  /// previous one.
  String get sessionId => _sessionId;

  /// Per-file progress. Broadcast, so several UI listeners are fine.
  ///
  /// Attach *before* calling [send] — a broadcast stream drops events for
  /// listeners that are not yet subscribed, and the first `accepted` events are
  /// emitted immediately after the offer comes back.
  Stream<FileProgress> get progress => _progress.stream;

  /// Runs a complete transfer: offer, negotiate, stream, verify, complete.
  ///
  /// [files] is whatever the user picked. A file the peer rejects does not fail
  /// the whole transfer; the reason is recorded in [SendResult.rejected] and the
  /// remaining files still go.
  ///
  /// Throws [PeerException] only when the session cannot proceed at all (offer
  /// rejected wholesale, transport down). Per-file problems are reported in
  /// [SendResult.failures] instead, because a 40-file drop failing because one
  /// file vanished mid-read is the wrong behaviour.
  Future<SendResult> send(List<LocalFile> files) async {
    if (_inFlight != null) {
      throw StateError('SenderSession $sessionId is already running');
    }
    final run = _run(files);
    _inFlight = run;
    try {
      return await run;
    } finally {
      _inFlight = null;
    }
  }

  /// Aborts the transfer and tells the peer to delete whatever it staged.
  ///
  /// Safe to call when nothing is running and safe to call twice. The
  /// `/v1/cancel` POST is best-effort: if the link is already gone there is
  /// nothing to tell, and the receiver's `onDisconnect` leaves staged files for
  /// resume anyway.
  Future<void> cancel() async {
    _cancelRequested = true;
    for (final id in _states.keys) {
      _emitRaw(id, TransferState.cancelled);
    }
    final running = _inFlight;
    if (running == null) return;
    try {
      await _link.requestJson(
        'POST',
        Api.cancel,
        body: {'sessionId': _sessionId, 'cancelled': true},
      );
    } on PeerException catch (e) {
      // The peer is already gone, or already cancelled. Not an error for us.
      coreLog.info('cancel: peer refused /v1/cancel (${e.code})');
    } on Object catch (e) {
      coreLog.info('cancel: could not reach the peer: $e');
    }
    // Swallow the worker's own failures: cancel is a caller-initiated abort, so
    // the in-flight send completing with `cancelled: true` is the expected
    // outcome, not a crash.
    await running.catchError((Object _) => _cancelledResult());
  }

  /// Releases the progress stream. Call when the UI is done with the session.
  Future<void> dispose() async {
    if (!_progress.isClosed) await _progress.close();
  }

  // ---------------------------------------------------------------------------
  // Orchestration
  // ---------------------------------------------------------------------------

  Future<SendResult> _run(List<LocalFile> files) async {
    if (_cancelRequested) return _cancelledResult();

    final entries = <FileEntry>[];
    for (final file in files) {
      final entry = file.toEntry();
      entries.add(entry);
      _states[entry.id] = TransferState.queued;
      _bytes[entry.id] = 0;
      _emitRaw(entry.id, TransferState.queued, entry: entry);
    }
    // Retained so throttled progress events can find the FileEntry a file id
    // refers to without the caller having to thread it through.
    _entries = entries;

    // Free-space pre-flight. Null means unknown on every native platform, in
    // which case the peer does its own check (and `stage` will fail loudly if it
    // guessed wrong).
    await _preflightSpace(entries);

    final total = entries.fold<int>(0, (a, e) => a + e.size);
    coreLog.info(
      'send: session $_sessionId, ${entries.length} files, '
      '${total ~/ 1024} KiB',
    );

    final Map<String, dynamic> raw;
    try {
      raw = await _link.requestJson(
        'POST',
        Api.offer,
        headers: {Header.sessionId: _sessionId},
        body: Offer(
          sessionId: _sessionId,
          files: entries,
          totalSize: total,
        ).toJson(),
      );
    } on PeerException catch (e) {
      for (final entry in entries) {
        _emitRaw(entry.id, TransferState.failed, entry: entry, error: e.code);
      }
      rethrow;
    }

    final answer = OfferResponse.fromJson(raw);
    for (final (id, reason) in answer.rejected) {
      final entry = entries.firstWhere(
        (e) => e.id == id,
        orElse: () => _emptyEntry(id),
      );
      _emitRaw(id, TransferState.skipped, entry: entry, error: reason.name);
      coreLog.info('send: peer rejected $id ($reason)');
    }

    final byId = {for (final e in entries) e.id: e};
    final queue = <LocalFile>[
      for (final id in answer.accepted)
        if (byId.containsKey(id)) files.firstWhere((f) => f.id == id),
    ];
    if (queue.isEmpty) {
      coreLog.info('send: nothing accepted');
      return SendResult(
        sessionId: _sessionId,
        completed: const [],
        rejected: answer.rejected,
        cancelled: _cancelRequested,
      );
    }

    // Resume offsets the peer volunteered. Anything not in the map starts at 0.
    final resume = <String, int>{};
    for (final id in answer.accepted) {
      final offset = answer.resume[id] ?? 0;
      if (offset > 0) resume[id] = offset;
    }

    final completed = <FileEntry>[];
    final failures = <String, String>{};

    // Fixed worker pool over a shared cursor. Each worker takes the next index,
    // so the pool self-balances: one slow file does not hold up the others.
    var cursor = 0;
    final workers = math.min(_maxParallel, queue.length);
    Future<void> worker() async {
      while (true) {
        if (_cancelRequested) return;
        final index = cursor++;
        if (index >= queue.length) return;
        final file = queue[index];
        final outcome = await _sendOne(file, resume[file.id] ?? 0);
        switch (outcome.status) {
          case _FileOutcome.ok:
            // The returned entry carries the digest we actually sent, which the
            // offered entry does not: the offer goes out before any file has
            // been hashed.
            if (outcome.entry != null) completed.add(outcome.entry!);
          case _FileOutcome.failed:
            failures[file.id] = outcome.error ?? 'transfer failed (see logs)';
          case _FileOutcome.skipped:
            // Cancelled mid-queue: the session is already flagged cancelled.
            break;
        }
      }
    }

    await Future.wait([for (var i = 0; i < workers; i++) worker()]);

    if (_cancelRequested) {
      return SendResult(
        sessionId: _sessionId,
        completed: completed,
        rejected: answer.rejected,
        cancelled: true,
      );
    }

    CompletionResult? verdict;
    if (failures.isEmpty) {
      try {
        final complete = await _link.requestJson(
          'POST',
          Api.complete,
          headers: {Header.sessionId: _sessionId},
          body: CompletionReport(
            sessionId: _sessionId,
            files: [
              for (final entry in completed)
                (entry.id, entry.sha256 ?? '', entry.size),
            ],
          ).toJson(),
        );
        verdict = CompletionResult.fromJson(complete);
        if (!verdict.ok) {
          for (final failure in verdict.failures) {
            final id = failure.split(':').first.trim();
            failures[id] = failure;
            _emitRaw(id, TransferState.failed, entry: byId[id], error: failure);
          }
        } else {
          for (final entry in completed) {
            _emitRaw(entry.id, TransferState.done, entry: entry);
          }
        }
      } on PeerException catch (e) {
        coreLog.warning('send: /v1/complete failed: ${e.code}');
        verdict = CompletionResult(
          ok: false,
          failures: ['${e.code}: ${e.message}'],
        );
      }
    }

    return SendResult(
      sessionId: _sessionId,
      completed: completed,
      rejected: answer.rejected,
      failures: failures,
      verdict: verdict,
    );
  }

  /// One file: hash it, then stream it.
  ///
  /// Two passes over the local file, deliberately:
  ///
  ///  * **Pass 1** computes SHA-256 so the digest can go in the request *header*.
  ///    HTTP cannot send a header after the body has started, so a digest is
  ///    needed before the first byte moves. The alternative — send first, verify
  ///    after — gives the receiver nothing to check against mid-flight and turns
  ///    corruption into a post-hoc surprise.
  ///  * **Pass 2** streams the bytes.
  ///
  /// Reading the file twice costs one extra sequential pass of local I/O
  /// (memory bandwidth, ~5 GB/s) and is far cheaper than the round trip a
  /// two-phase "declare digest, then transfer" handshake would cost.
  ///
  /// For a resumed send the *prefix* is not re-sent but is still hashed in pass
  /// 1, because the digest covers the whole file.
  Future<_FileResult> _sendOne(LocalFile file, int resumeFrom) async {
    final entry = file.toEntry();
    _states[file.id] = TransferState.transferring;
    _emitRaw(file.id, TransferState.transferring, entry: entry);

    try {
      // Pass 1: hash the whole file so the digest can travel in the request
      // header. On a resumed send the already-delivered prefix is hashed here
      // even though it will not be re-sent, because the digest covers the whole
      // file.
      final digest = await _digestOf(file, resumeFrom);
      if (_cancelRequested) return const _FileResult.skipped();

      // From here on every progress event carries the digest, so a UI showing
      // "verifying: <sha>" shows the value that was actually sent.
      final updated = file.toEntry(sha256: digest);
      final total = file.size;

      var from = resumeFrom;
      for (var attempt = 0; attempt <= _maxResumeAttempts; attempt++) {
        if (_cancelRequested) return const _FileResult.skipped();
        _states[file.id] = TransferState.transferring;
        _emitRaw(file.id, TransferState.transferring, entry: updated);

        coreLog.info(
          'send: ${file.name} -> ${Api.fileStatus(file.id)} '
          'from $from/$total (sha256 ${digest.substring(0, 12)}…)',
        );

        try {
          final response = await _link.putStream(
            Api.fileStatus(file.id),
            _reader.chunkedFileStream(file.path, fromOffset: from),
            contentLength: total - from,
            headers: {
              Header.sha256: digest,
              Header.sessionId: _sessionId,
              if (from > 0) Header.contentRange: 'bytes=$from-',
            },
            onProgress: (sent) {
              _emit(file.id, from + sent, entry: updated);
            },
          );

          if (response['sha256Match'] == false) {
            coreLog.warning(
              'send: receiver rejected the digest of ${file.name}',
            );
            _emitRaw(
              file.id,
              TransferState.failed,
              entry: updated,
              error: ApiError.hashMismatch,
            );
            return _FileResult.failed(
              'receiver rejected the digest (${ApiError.hashMismatch})',
            );
          }

          _states[file.id] = TransferState.verifying;
          _bytes[file.id] = total;
          _emitRaw(file.id, TransferState.done, entry: updated);
          return _FileResult.ok(updated);
        } on PeerException catch (e) {
          // A 409 means our idea of the resume point disagreed with the
          // receiver's. Rather than failing the file — or worse, blindly
          // restarting from zero and re-sending gigabytes — ask the peer where
          // it actually is and seek there.
          if (e.code != ApiError.conflict || attempt == _maxResumeAttempts) {
            rethrow;
          }
          final offset = await _resumeOffsetFrom(file.id);
          if (offset == null || offset <= from || offset > total) {
            coreLog.warning(
              'send: ${file.name} conflicts at $from and the peer will not '
              'give a usable resume point (${offset ?? 'null'}); giving up',
            );
            rethrow;
          }
          coreLog.info(
            'send: ${file.name} conflicts at $from; seeking to $offset',
          );
          from = offset;
        }
      }

      return _FileResult.failed('resume attempts exhausted');
    } on PeerException catch (e) {
      if (_cancelRequested) return const _FileResult.skipped();
      coreLog.warning('send: ${file.name} failed: ${e.code} ${e.message}');
      final reason = '${e.code}${e.message.isEmpty ? '' : ': ${e.message}'}';
      _emitRaw(file.id, TransferState.failed, entry: entry, error: reason);
      return _FileResult.failed(reason);
    } on Object catch (e) {
      if (_cancelRequested) return const _FileResult.skipped();
      coreLog.warning('send: ${file.name} failed', e);
      _emitRaw(file.id, TransferState.failed, entry: entry, error: '$e');
      return _FileResult.failed('$e');
    }
  }

  /// Asks the peer how much of a file it has actually stored.
  ///
  /// `GET /v1/file/{id}` rather than parsing `resumeFrom` out of the 409's
  /// message: [PeerLink.requestJson] turns a non-2xx status into a
  /// [PeerException] carrying only the machine-readable code, so the body is not
  /// reachable through the frozen contract. The extra round trip costs one
  /// packet on a path that only happens after a failure.
  ///
  /// Returns `null` when the peer cannot be asked, or when it claims an
  /// impossible offset — a resume past the real file would produce a file that
  /// fails verification, and a resume behind where we already are would loop.
  Future<int?> _resumeOffsetFrom(String fileId) async {
    try {
      final status = await _link.getJson(Api.fileStatus(fileId));
      final received = (status['received'] as num?)?.toInt();
      final size = (status['size'] as num?)?.toInt();
      if (received == null) return null;
      if (size != null && received > size) return null;
      return received;
    } on PeerException catch (e) {
      coreLog.info(
        'send: could not read the resume point for $fileId '
        '(${e.code})',
      );
      return null;
    } on Object catch (e) {
      coreLog.warning('send: could not read the resume point for $fileId', e);
      return null;
    }
  }

  /// SHA-256 of the whole local file, read through the [ChunkedFileReader] so no
  /// `dart:io` handle is opened directly (a browser build has no `File`).
  ///
  /// On a resumed send this is two sequential passes over `[0, resumeFrom)` and
  /// `[resumeFrom, end)` rather than one interleaved walk. Same bytes hashed,
  /// same order, but no cursor bookkeeping to get wrong — and the prefix pass
  /// also feeds progress events, because the user should see the bar move while
  /// we are checking bytes we are *not* about to send.
  Future<String> _digestOf(LocalFile file, int resumeFrom) async {
    final sink = Sha256().newHashSink();
    final entry = file.toEntry();

    var hashed = 0;
    if (resumeFrom > 0) {
      await for (final chunk in _reader.chunkedFileStream(file.path)) {
        final take = math.min(chunk.length, resumeFrom - hashed);
        if (take <= 0) break; // prefix fully hashed; the tail pass takes over
        if (take == chunk.length) {
          sink.add(chunk);
        } else {
          sink.add(chunk.sublist(0, take));
        }
        hashed += take;
        _emit(file.id, hashed, entry: entry);
        if (hashed >= resumeFrom) break;
      }
      await for (final chunk in _reader.chunkedFileStream(
        file.path,
        fromOffset: resumeFrom,
      )) {
        sink.add(chunk);
        hashed += chunk.length;
        _emit(file.id, hashed, entry: entry);
      }
    } else {
      await for (final chunk in _reader.chunkedFileStream(file.path)) {
        sink.add(chunk);
        hashed += chunk.length;
        // Progress during hashing, not just while sending: on a fast disk the
        // hash pass is a visible fraction of the total time and a frozen bar
        // during it reads as a hang.
        _emit(file.id, hashed, entry: entry);
      }
    }

    sink.close();
    return _hex((await sink.hash()).bytes);
  }

  /// Local capacity check before bothering the peer.
  ///
  /// `freeSpace()` is `null` on every native target (no statvfs in `dart:io`), so
  /// this normally does nothing and the check happens on the receiving side
  /// instead. It stays because a platform-specific store *can* answer, and
  /// failing before the offer beats failing after 40 GiB of upload.
  Future<void> _preflightSpace(List<FileEntry> entries) async {
    final free = await _store.freeSpace();
    if (free == null) return;
    final need =
        (entries.fold<int>(0, (a, e) => a + e.size) *
                Transfer.requiredFreeSpaceFactor)
            .ceil();
    if (free < need) {
      throw AeroException(
        'not enough local space to stage $need bytes (have $free)',
      );
    }
  }

  SendResult _cancelledResult() =>
      SendResult(sessionId: _sessionId, completed: const [], cancelled: true);

  // ---------------------------------------------------------------------------
  // Progress emission
  // ---------------------------------------------------------------------------

  /// Throttled progress update.
  ///
  /// Two suppressions, both deliberate:
  ///
  ///  * **Rate limit.** One event per [_progressInterval] per file. A 1 GB/s
  ///    link on 4 MiB chunks would otherwise produce ~250 events/second, each
  ///    one a `setState` in the UI and a rebuild of the row's subtree. Ten per
  ///    second is already smoother than a 60 Hz screen can show.
  ///  * **Monotonicity.** An update that does not advance the counter is dropped,
  ///    so a stalled file emits nothing rather than a stream of identical
  ///    events that still cost a rebuild.
  ///
  /// State *transitions* bypass the throttle entirely (via [_emitRaw]) because
  /// they are rare and semantically important — a row must not sit on
  /// "transferring" forever just because its bytes have not moved.
  void _emit(String id, int bytes, {FileEntry? entry}) {
    final previous = _bytes[id] ?? 0;
    if (bytes <= previous &&
        !(entry?.size != null && entry!.size > 0 && bytes == entry.size)) {
      return;
    }
    _bytes[id] = bytes;
    final now = DateTime.now();
    final last = _lastProgress[id];
    if (last != null && now.difference(last) < _progressInterval) return;
    _lastProgress[id] = now;
    final target = entry ?? _entryFor(id);
    if (target == null) return;
    _publish(
      FileProgress(
        entry: target,
        state: _states[id] ?? TransferState.transferring,
        bytesTransferred: bytes,
      ),
    );
  }

  /// Unthrottled event, for state transitions and terminal states.
  void _emitRaw(
    String id,
    TransferState state, {
    FileEntry? entry,
    String? error,
  }) {
    _states[id] = state;
    if (state == TransferState.done) {
      _bytes[id] = entry?.size ?? _bytes[id] ?? 0;
    }
    final target = entry ?? _entryFor(id);
    if (target == null) return;
    _lastProgress[id] = DateTime.now();
    _publish(
      FileProgress(
        entry: target,
        state: state,
        bytesTransferred: _bytes[id] ?? 0,
        error: error,
      ),
    );
  }

  void _publish(FileProgress event) {
    if (_progress.isClosed) return;
    // The controller is broadcast, so `add` is fire-and-forget. A slow or
    // erroring listener must never stall the transfer.
    _progress.add(event);
  }

  FileEntry? _entryFor(String id) {
    for (final entry in _entries) {
      if (entry.id == id) return entry;
    }
    return null;
  }

  List<FileEntry> _entries = const [];

  static FileEntry _emptyEntry(String id) =>
      FileEntry(id: id, name: '', size: 0);
}

/// Why a single file ended the way it did, plus what we learned doing it.
///
/// Internal: [SendResult] is the public shape. [entry] exists so a successful
/// send can report the digest it actually streamed, which the offered entry does
/// not carry — the offer is sent before any file has been hashed.
enum _FileOutcome { ok, failed, skipped }

class _FileResult {
  const _FileResult.ok(this.entry) : status = _FileOutcome.ok, error = null;
  const _FileResult.failed(this.error)
    : status = _FileOutcome.failed,
      entry = null;
  const _FileResult.skipped()
    : status = _FileOutcome.skipped,
      entry = null,
      error = null;

  final _FileOutcome status;
  final FileEntry? entry;
  final String? error;
}

/// Lowercase hex, so we do not depend on `package:convert` for 32 bytes.
///
/// `StringBuffer()` starts empty on purpose: its constructor takes *content*, not
/// capacity, so passing a length would prepend its decimal form to the digest.
String _hex(List<int> bytes) {
  const digits = '0123456789abcdef';
  final out = StringBuffer();
  for (final b in bytes) {
    out.writeCharCode(digits.codeUnitAt((b >> 4) & 0x0f));
    out.writeCharCode(digits.codeUnitAt(b & 0x0f));
  }
  return out.toString();
}
